import { writeFile } from "node:fs/promises";
import { setTimeout as pause } from "node:timers/promises";
import { AMENDMENTS_PAGE_URL, parseAmendmentPage, extractAmendedKokujiKeys, preferredAmendmentDocument, hasCompletePdfTargets } from "../dist/lib/kokuji-amendments.js";
import { fetchMlitText } from "../dist/lib/mlit-client.js";
import { SERVER_VERSION } from "../dist/lib/version.js";
import * as pdfjs from "pdfjs-dist/legacy/build/pdf.mjs";

const html = await fetchMlitText(AMENDMENTS_PAGE_URL);
const notices = html ? parseAmendmentPage(html) : [];
if (notices.length === 0) throw new Error("改正ページを取得・解析できませんでした。索引は更新していません。");
const index = {};
const failures = [];
// Allow an explicit omission when a previous build has already proved a PDF unreadable.
const skippedPdfs = new Set(process.argv.slice(2).filter((arg) => arg.startsWith("--skip-pdf=")).map((arg) => arg.slice("--skip-pdf=".length)));
let readCount = 0;
for (const notice of notices) {
  const document = preferredAmendmentDocument(notice);
  if (!document || !notice.key) {
    failures.push({ number: notice.number, url: document?.url ?? null, error: "対象PDFまたは告示番号なし" });
    continue;
  }
  // Keep negative results too, so runtime never repeats a known build-time read.
  index[notice.key] = { number: notice.number, source_pdf: document.url, target_keys: [], complete: false };
  if (skippedPdfs.has(document.url)) {
    const failure = { number: notice.number, url: document.url, error: "前回の読取失敗により再取得を省略しました" };
    failures.push(failure);
    console.error(JSON.stringify(failure));
    continue;
  }
  let task;
  try {
    const url = new URL(document.url);
    if (url.origin !== "https://www.mlit.go.jp" || url.username || url.password) throw new Error("許可されていないURLです");
    const response = await fetch(url, {
      headers: { "User-Agent": `BuildingStandardsActMCP/${SERVER_VERSION}` },
      signal: AbortSignal.timeout(30_000), redirect: "error",
    });
    if (!response.ok) throw new Error(`HTTP ${response.status}`);
    const data = new Uint8Array(await response.arrayBuffer());
    task = pdfjs.getDocument({ data, cMapUrl: "./node_modules/pdfjs-dist/cmaps/", cMapPacked: true });
    const pdf = await task.promise;
    let text = "";
    for (let pageNumber = 1; pageNumber <= pdf.numPages; pageNumber++) {
      const page = await pdf.getPage(pageNumber);
      const content = await page.getTextContent();
      text += content.items.map((item) => item.str ?? "").join("") + "\n";
      page.cleanup();
    }
    if (!text.trim()) throw new Error("PDFからテキストを抽出できませんでした");
    readCount++;
    const targetKeys = extractAmendedKokujiKeys(text);
    const complete = hasCompletePdfTargets(notice, targetKeys);
    index[notice.key] = { number: notice.number, source_pdf: document.url, target_keys: targetKeys, complete };
    if (!complete) throw new Error("PDF本文は読取済みですが、改正対象を確定できませんでした");
    console.log(`読取成功 ${readCount}: ${notice.number}（対象 ${index[notice.key].target_keys.length} 件）`);
  } catch (error) {
    const failure = { number: notice.number, url: document.url, error: error instanceof Error ? error.message : String(error) };
    failures.push(failure);
    console.error(JSON.stringify(failure));
  } finally {
    await task?.destroy();
    await pause(200);
  }
}
const output = { generated_on: new Date().toISOString().slice(0, 10), notices: Object.fromEntries(Object.entries(index).sort(([a], [b]) => a.localeCompare(b))) };
const type = "{ generated_on: string; notices: Record<string, { number: string; source_pdf: string; target_keys: string[]; complete: boolean }> }";
await writeFile(new URL("../src/data/kokuji-amendment-index.ts", import.meta.url),
  "// Amendment-to-target relations are immutable historical facts, so this index is committed.\n"
  + "// Generated by scripts/build-kokuji-amendment-index.mjs. Do not edit manually.\n"
  + `export const KOKUJI_AMENDMENT_INDEX: ${type} = ${JSON.stringify(output, null, 2)};\n`, "utf8");
console.log(JSON.stringify({ notices_total: notices.length, pdfs_read_ok: readCount, notices_indexed: Object.keys(index).length, failures }, null, 2));
